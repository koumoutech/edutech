/**
 * Generates `src/types/database.ts` (supabase-js `Database` shape) by introspecting a
 * PostgreSQL database that has the migrations applied.
 *
 * Equivalent to `supabase gen types typescript`, usable without Docker:
 *   TEST_DATABASE_URL=postgres://... pnpm db:types
 */
import { writeFileSync } from "node:fs";
import { Client } from "pg";

const url = process.env.TEST_DATABASE_URL ?? process.env.DATABASE_URL;
if (!url) {
  console.error("TEST_DATABASE_URL is required");
  process.exit(1);
}

const PG_TO_TS: Record<string, string> = {
  uuid: "string",
  text: "string",
  varchar: "string",
  bpchar: "string",
  citext: "string",
  date: "string",
  time: "string",
  timetz: "string",
  timestamp: "string",
  timestamptz: "string",
  interval: "string",
  int4range: "unknown",
  bool: "boolean",
  int2: "number",
  int4: "number",
  int8: "number",
  float4: "number",
  float8: "number",
  numeric: "number",
  json: "Json",
  jsonb: "Json",
  bytea: "string",
  void: "undefined",
  record: "Json",
};

function tsType(udt: string): string {
  if (udt.startsWith("_")) return `${tsType(udt.slice(1))}[]`;
  return PG_TO_TS[udt] ?? "unknown";
}

async function main() {
  const client = new Client({ connectionString: url });
  await client.connect();

  const columns = (
    await client.query<{
      table_name: string;
      column_name: string;
      udt_name: string;
      is_nullable: "YES" | "NO";
      column_default: string | null;
      is_generated: string;
      is_identity: string;
      table_type: string;
    }>(`
      select c.table_name, c.column_name, c.udt_name, c.is_nullable, c.column_default, c.is_generated, c.is_identity, t.table_type
      from information_schema.columns c
      join information_schema.tables t on t.table_schema = c.table_schema and t.table_name = c.table_name
      where c.table_schema = 'public'
      order by c.table_name, c.ordinal_position`)
  ).rows;

  const fks = (
    await client.query<{
      constraint_name: string;
      table_name: string;
      columns: string[];
      ref_table: string;
      ref_columns: string[];
      one_to_one: boolean;
    }>(`
      select con.conname as constraint_name, cl.relname as table_name,
        array(select a.attname from unnest(con.conkey) with ordinality k(n, o) join pg_attribute a on a.attrelid = con.conrelid and a.attnum = k.n order by k.o)::text[] as columns,
        rcl.relname as ref_table,
        array(select a.attname from unnest(con.confkey) with ordinality k(n, o) join pg_attribute a on a.attrelid = con.confrelid and a.attnum = k.n order by k.o)::text[] as ref_columns,
        exists (
          select 1 from pg_index i where i.indrelid = con.conrelid and i.indisunique
            and (select array_agg(x order by x) from unnest(i.indkey::int2[]) x) = (select array_agg(x order by x) from unnest(con.conkey) x)
        ) as one_to_one
      from pg_constraint con
      join pg_class cl on cl.oid = con.conrelid
      join pg_namespace n on n.oid = cl.relnamespace
      join pg_class rcl on rcl.oid = con.confrelid
      join pg_namespace rn on rn.oid = rcl.relnamespace
      where con.contype = 'f' and n.nspname = 'public' and rn.nspname = 'public'
      order by cl.relname, con.conname`)
  ).rows;

  const functions = (
    await client.query<{
      name: string;
      args: { name: string; type: string; has_default: boolean }[];
      returns_set: boolean;
      return_type: string;
      table_columns: { name: string; type: string }[] | null;
    }>(`
      select p.proname as name,
        coalesce((
          select json_agg(json_build_object('name', p.proargnames[i], 'type', t.typname, 'has_default', i > p.pronargs - p.pronargdefaults) order by i)
          from generate_series(1, p.pronargs) i
          join pg_type t on t.oid = p.proargtypes[i - 1]
        ), '[]') as args,
        p.proretset as returns_set,
        rt.typname as return_type,
        (
          select json_agg(json_build_object('name', p.proargnames[i], 'type', t.typname) order by i)
          from generate_series(1, coalesce(array_length(p.proallargtypes, 1), 0)) i
          join pg_type t on t.oid = p.proallargtypes[i]
          where p.proargmodes[i] = 't'
        ) as table_columns
      from pg_proc p
      join pg_namespace n on n.oid = p.pronamespace
      join pg_type rt on rt.oid = p.prorettype
      where n.nspname = 'public' and p.prokind = 'f' and rt.typname <> 'trigger'
      order by p.proname`)
  ).rows;

  await client.end();

  const tables = new Map<string, typeof columns>();
  for (const c of columns) {
    if (!tables.has(c.table_name)) tables.set(c.table_name, []);
    tables.get(c.table_name)!.push(c);
  }

  const out: string[] = [];
  out.push("// AUTO-GENERATED by scripts/gen-db-types.ts — do not edit by hand.");
  out.push("export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];");
  out.push("");
  out.push("export type Database = {");
  out.push("  public: {");
  out.push("    Tables: {");
  for (const [name, cols] of tables) {
    if (cols[0].table_type !== "BASE TABLE") continue;
    out.push(`      ${name}: {`);
    out.push("        Row: {");
    for (const c of cols)
      out.push(`          ${c.column_name}: ${tsType(c.udt_name)}${c.is_nullable === "YES" ? " | null" : ""};`);
    out.push("        };");
    out.push("        Insert: {");
    for (const c of cols) {
      if (c.is_generated === "ALWAYS") {
        out.push(`          ${c.column_name}?: never;`);
        continue;
      }
      const optional = c.is_nullable === "YES" || c.column_default !== null || c.is_identity === "YES";
      out.push(
        `          ${c.column_name}${optional ? "?" : ""}: ${tsType(c.udt_name)}${c.is_nullable === "YES" ? " | null" : ""};`,
      );
    }
    out.push("        };");
    out.push("        Update: {");
    for (const c of cols) {
      if (c.is_generated === "ALWAYS") {
        out.push(`          ${c.column_name}?: never;`);
        continue;
      }
      out.push(`          ${c.column_name}?: ${tsType(c.udt_name)}${c.is_nullable === "YES" ? " | null" : ""};`);
    }
    out.push("        };");
    out.push("        Relationships: [");
    for (const fk of fks.filter((f) => f.table_name === name)) {
      out.push("          {");
      out.push(`            foreignKeyName: ${JSON.stringify(fk.constraint_name)};`);
      out.push(`            columns: ${JSON.stringify(fk.columns)};`);
      out.push(`            isOneToOne: ${fk.one_to_one};`);
      out.push(`            referencedRelation: ${JSON.stringify(fk.ref_table)};`);
      out.push(`            referencedColumns: ${JSON.stringify(fk.ref_columns)};`);
      out.push("          },");
    }
    out.push("        ];");
    out.push("      };");
  }
  out.push("    };");
  out.push("    Views: { [_ in never]: never };");
  out.push("    Functions: {");
  const byName = new Map<string, typeof functions>();
  for (const f of functions) {
    if (!byName.has(f.name)) byName.set(f.name, []);
    byName.get(f.name)!.push(f);
  }
  for (const [name, overloads] of byName) {
    const f = overloads[0];
    const args = f.args.filter((a) => a.name);
    const argsTs = args.length
      ? `{ ${args.map((a) => `${a.name}${a.has_default ? "?" : ""}: ${tsType(a.type)}`).join("; ")} }`
      : "Record<PropertyKey, never>";
    let ret: string;
    if (f.table_columns && f.table_columns.length) {
      ret = `{ ${f.table_columns.map((c) => `${c.name}: ${tsType(c.type)}`).join("; ")} }[]`;
    } else {
      ret = tsType(f.return_type) + (f.returns_set ? "[]" : "");
    }
    out.push(`      ${name}: { Args: ${argsTs}; Returns: ${ret} };`);
  }
  out.push("    };");
  out.push("    Enums: { [_ in never]: never };");
  out.push("    CompositeTypes: { [_ in never]: never };");
  out.push("  };");
  out.push("};");
  out.push("");
  out.push(
    'export type Tables<T extends keyof Database["public"]["Tables"]> = Database["public"]["Tables"][T]["Row"];',
  );
  out.push(
    'export type TablesInsert<T extends keyof Database["public"]["Tables"]> = Database["public"]["Tables"][T]["Insert"];',
  );
  out.push(
    'export type TablesUpdate<T extends keyof Database["public"]["Tables"]> = Database["public"]["Tables"][T]["Update"];',
  );
  out.push('export type DbFunctions = Database["public"]["Functions"];');
  out.push("");

  writeFileSync(new URL("../src/types/database.ts", import.meta.url), out.join("\n"));
  console.log(`Generated ${tables.size} tables, ${byName.size} functions.`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});

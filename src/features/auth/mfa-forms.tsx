"use client";

import { ShieldCheckIcon, ShieldOffIcon } from "lucide-react";
import { useActionState, useState, useTransition } from "react";
import { toast } from "sonner";
import { ActionMessage, fieldError, SubmitButton } from "@/components/form-status";
import { Button } from "@/components/ui/button";
import { Field, Input } from "@/components/ui/form-controls";
import { confirmMfaEnrollment, disableMfa, startMfaEnrollment, verifyMfaChallenge } from "./mfa-actions";

const codeInputProps = {
  inputMode: "numeric" as const,
  autoComplete: "one-time-code",
  pattern: "[0-9]{6}",
  maxLength: 6,
  required: true,
  className: "text-center font-mono text-lg tracking-[0.4em]",
};

export function MfaChallengeForm({ next }: { next: string }) {
  const [state, action] = useActionState(verifyMfaChallenge, null);
  return (
    <form action={action} className="space-y-4">
      <ActionMessage state={state} />
      <input type="hidden" name="next" value={next} />
      <Field label="Code à 6 chiffres" htmlFor="mfa-code" error={fieldError(state, "code")}>
        <Input id="mfa-code" name="code" autoFocus {...codeInputProps} />
      </Field>
      <SubmitButton className="w-full" size="lg" pendingLabel="Vérification…">
        Valider
      </SubmitButton>
    </form>
  );
}

export function MfaSettings({ enabled }: { enabled: boolean }) {
  const [pending, start] = useTransition();
  const [enrolment, setEnrolment] = useState<{ factorId: string; qrCode: string; secret: string } | null>(null);
  const [code, setCode] = useState("");
  const [disabling, setDisabling] = useState(false);

  if (enabled && !disabling) {
    return (
      <div className="flex flex-wrap items-center gap-3">
        <p className="text-primary flex items-center gap-2 text-sm font-medium">
          <ShieldCheckIcon className="size-4" aria-hidden /> Double authentification activée
        </p>
        <Button variant="outline" size="sm" onClick={() => setDisabling(true)}>
          <ShieldOffIcon /> Désactiver
        </Button>
      </div>
    );
  }

  if (enabled && disabling) {
    return (
      <form
        className="flex flex-wrap items-end gap-2"
        onSubmit={(e) => {
          e.preventDefault();
          start(async () => {
            const res = await disableMfa(code);
            if (res.ok) {
              toast.success(res.message ?? "Désactivée.");
              setDisabling(false);
              setCode("");
            } else toast.error(res.error);
          });
        }}
      >
        <Field label="Code actuel de votre application" htmlFor="mfa-off">
          <Input id="mfa-off" value={code} onChange={(e) => setCode(e.target.value)} {...codeInputProps} />
        </Field>
        <Button type="submit" variant="destructive" disabled={pending}>
          Confirmer la désactivation
        </Button>
        <Button type="button" variant="ghost" onClick={() => setDisabling(false)}>
          Annuler
        </Button>
      </form>
    );
  }

  if (!enrolment) {
    return (
      <div className="space-y-2">
        <p className="text-muted-foreground text-sm">
          Protégez votre compte avec un code temporaire généré par une application (Google Authenticator, Microsoft
          Authenticator, FreeOTP…). Fortement recommandé pour les profils de direction, finances et administration.
        </p>
        <Button
          disabled={pending}
          onClick={() =>
            start(async () => {
              const res = await startMfaEnrollment();
              if (res.ok) setEnrolment(res.data);
              else toast.error(res.error);
            })
          }
        >
          <ShieldCheckIcon /> Activer la double authentification
        </Button>
      </div>
    );
  }

  return (
    <form
      className="space-y-3"
      onSubmit={(e) => {
        e.preventDefault();
        start(async () => {
          const res = await confirmMfaEnrollment(enrolment.factorId, code);
          if (res.ok) {
            toast.success(res.message ?? "Activée.");
            setEnrolment(null);
            setCode("");
          } else toast.error(res.error);
        });
      }}
    >
      <p className="text-sm">1. Scannez ce QR code avec votre application d&apos;authentification.</p>
      {/* eslint-disable-next-line @next/next/no-img-element -- data: URI SVG generated by Supabase Auth */}
      <img src={enrolment.qrCode} alt="QR code de configuration" className="size-44 rounded-lg bg-white p-2" />
      <p className="text-muted-foreground text-xs">
        Ou saisissez cette clé : <code className="font-mono break-all select-all">{enrolment.secret}</code>
      </p>
      <Field label="2. Saisissez le code affiché" htmlFor="mfa-new">
        <Input id="mfa-new" value={code} onChange={(e) => setCode(e.target.value)} {...codeInputProps} />
      </Field>
      <div className="flex gap-2">
        <Button type="submit" disabled={pending}>
          Confirmer
        </Button>
        <Button type="button" variant="ghost" onClick={() => setEnrolment(null)}>
          Annuler
        </Button>
      </div>
    </form>
  );
}
